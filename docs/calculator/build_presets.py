#!/usr/bin/env python3
"""Copy the pricing presets (core/pricing/*.json) into presets.js for the web calculator."""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))

presets = {}
for path in sorted(glob.glob(os.path.join(ROOT, "core", "pricing", "*.json"))):
    with open(path, encoding="utf-8") as f:
        d = json.load(f)
    presets[os.path.basename(path)[:-5]] = {
        "label": f"{d['vendor']} · {d['model']}",
        "per_million": d["per_million"],
        "long_context_threshold": d.get("long_context_threshold"),
        "long_context_per_million": d.get("long_context_per_million"),
        "checked": d.get("checked"),
    }
with open(os.path.join(HERE, "presets.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by build_presets.py from core/pricing/*.json. Do not edit by hand.\n")
    f.write("export const PRESETS = " + json.dumps(presets, ensure_ascii=False, indent=2) + ";\n")
print(f"{len(presets)} presets")
